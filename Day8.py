# List Operations
a = [10, 20]
b = [30, 40]
print(a + b)
print(["Python", "Java"] * 2)
numbers = [15, 25, 35, 45]
print(numbers[0])      # First element
print(numbers[-1])     # Last element
numbers = [10, 20, 30, 40, 50]
print(numbers[1:4])    # Slicing
print(numbers[::-1])   # Reverse list
numbers = [10, 20, 30]
print(20 in numbers)
print(50 not in numbers)
# Nested Lists
students = [["Ravi", 21], ["Sita", 22]]
print(students[0])
print(students[1][0])
# Tuple Operations
a = (10, 20)
b = (30, 40)
print(a + b)


print(("Python", "Java") * 2)


data = (100, 200, 300, 400)

print(data[0])         # First element
print(data[-1])        # Last element


data = (10, 20, 30, 40, 50)

print(data[1:4])       # Slicing
print(data[::-1])      # Reverse tuple


data = (10, 20, 30)

print(20 in data)
print(50 not in data)